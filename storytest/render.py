"""Render a TestPlan as Markdown, a Playwright spec, and a locator contract."""
from __future__ import annotations

import json

from .models import TestPlan


def _esc_ts(text: str) -> str:
    return text.replace("\\", "\\\\").replace("'", "\\'")


def to_markdown(plan: TestPlan) -> str:
    cov = ", ".join(f"{k}: {v}" for k, v in sorted(plan.coverage().items()))
    out = [f"# Test plan: {plan.story_id} - {plan.title}", "", plan.summary, "",
           f"**Coverage:** {cov}", ""]
    if plan.risks:
        out += ["## Risks", *[f"- {r}" for r in plan.risks], ""]
    out += ["## Scenarios", "", "| ID | Title | Type | Priority | Level | Automate |",
            "|---|---|---|---|---|---|"]
    for s in plan.scenarios:
        out.append(f"| {s.id} | {s.title.replace('|', '/')} | {s.type} | {s.priority} | {s.level} | "
                   f"{'yes' if s.automate else 'no'} |")
    out.append("")
    for s in plan.scenarios:
        out += [f"### {s.id}: {s.title}"]
        if s.criterion:
            out.append(f"_Covers: {s.criterion}_")
        if s.preconditions:
            out += ["", "**Preconditions**", *[f"- {p}" for p in s.preconditions]]
        out += ["", "**Steps**", *[f"{i}. {st}" for i, st in enumerate(s.steps, 1)],
                "", "**Expected**", *[f"- {e}" for e in s.expected], ""]
    if plan.locators:
        out += ["## Locator contract", "", "| Element | data-testid | Role |", "|---|---|---|",
                *[f"| {l.name} | `{l.test_id}` | {l.role or '-'} |" for l in plan.locators], ""]
    if plan.open_questions:
        out += ["## Open questions", *[f"- {q}" for q in plan.open_questions], ""]
    return "\n".join(out)


def to_playwright(plan: TestPlan) -> str:
    """Generate a Playwright Test spec. API scenarios use the `request` fixture."""
    lines = [
        "// Generated by storytest. Fill in the TODOs, then remove test.fixme.",
        "import { test, expect } from '@playwright/test';",
        "",
    ]
    if plan.locators:
        lines.append("const ids = {")
        for l in plan.locators:
            key = "".join(w.capitalize() if i else w for i, w in enumerate(l.test_id.split("-")))
            lines.append(f"  {key}: '{_esc_ts(l.test_id)}', // {l.name}")
        lines += ["} as const;", ""]
    lines.append(f"test.describe('{_esc_ts(plan.story_id)}: {_esc_ts(plan.title)}', () => {{")
    for s in plan.scenarios:
        if not s.automate or s.level not in ("ui", "api"):
            continue
        fixture = "{ page }" if s.level == "ui" else "{ request }"
        tags = f"@{s.priority.lower()} @{s.type}"
        lines.append(f"  test('{s.id} {_esc_ts(s.title)} {tags}', async ({fixture}) => {{")
        lines.append("    test.fixme(true, 'Generated skeleton: implement steps');")
        for st in s.steps:
            lines.append(f"    await test.step('{_esc_ts(st)}', async () => {{")
            lines.append("      // TODO")
            lines.append("    });")
        for e in s.expected:
            lines.append(f"    // expect: {e}")
        lines.append("  });")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("});")
    return "\n".join(lines) + "\n"


def to_locator_contract(plan: TestPlan) -> str:
    return json.dumps({"story": plan.story_id,
                       "locators": [{"name": l.name, "data-testid": l.test_id, "role": l.role}
                                    for l in plan.locators]}, indent=2) + "\n"
